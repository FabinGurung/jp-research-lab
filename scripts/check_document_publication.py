#!/usr/bin/env python3
"""Shared publication-language screen; does not certify factual truth."""
import argparse,json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
POLICY=ROOT/"controls/document-publication.policy.json"
def findings(text):
    policy=json.loads(POLICY.read_text(encoding="utf-8"))
    return [p["id"] for p in policy["patterns"] if re.search(p["regex"],text,re.I)]
def self_test():
    assert findings("Generated by ChatGPT for review")
    assert findings("Internal QA checklist")
    assert not findings("ChatGPT was evaluated as an experimental model.")
    assert not findings("AI assistance is disclosed as required by the university.")
    assert not findings("The measurement uncertainty limits interpretation.")
    assert not findings("Draft agreement subject to legal review.")
    print("PASS shared publication-language context examples")
if __name__=="__main__":
    ap=argparse.ArgumentParser()
    ap.add_argument("--self-test",action="store_true")
    ap.add_argument("--text-file",type=Path)
    args=ap.parse_args()
    if args.self_test: self_test()
    elif args.text_file:
        hits=findings(args.text_file.read_text(encoding="utf-8"))
        print(json.dumps({"review_required":hits,"scientific_or_legal_approval":False}))
        if hits: raise SystemExit(1)
    else: ap.error("Use --self-test or --text-file")
